#
# Perfect for Data Science:
# - Interactive coding
# - Great for learning
# - Web-based interface
#
# Install:
#   pip install jupyterlab
#   jupyter lab

# 3️⃣ PyCharm
#
# - Professional IDE
# - More features
# - Can be overwhelming for beginners

# ------------------------------------------------
# ✅ My Recommendation
# ------------------------------------------------
